def geocode_location(location_text: str):
    """Look up GPS coordinates from a location string.

    Tries exact match first, then searches for any known city/district
    name within the text. Case-insensitive.

    Returns (latitude, longitude) or None.
    """
    if not location_text:
        return None

    text = location_text.strip().lower()

    # Exact match
    if text in KOREA_GEOCODE:
        return KOREA_GEOCODE[text]

    # Search for known names within the text
    # Try longest matches first to prefer "chungju" over "chung"
    for name in sorted(KOREA_GEOCODE.keys(), key=len, reverse=True):
        if name in text:
            return KOREA_GEOCODE[name]

    return None
